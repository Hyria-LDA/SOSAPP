import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const actor='00000000-0000-0000-0000-000000000001';
const owner='00000000-0000-0000-0000-000000000002';
const material='00000000-0000-0000-0000-000000000003';
const migration=await readFile(new URL('../supabase/migrations/20261119120000_reject_material_with_reason.sql',import.meta.url),'utf8');
test('rejection is admin-only, atomic, preserves the explanation and is idempotent',async()=>{
 const db=new PGlite();
 try {
 await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
 INSERT INTO auth.users VALUES('${actor}'),('${owner}');
 CREATE FUNCTION public.has_role(uuid,text) RETURNS boolean LANGUAGE sql AS $$ SELECT $1='${actor}'::uuid AND $2='admin' $$;
 CREATE TABLE empresas(id uuid PRIMARY KEY,owner_id uuid);
 CREATE TABLE materiais(id uuid PRIMARY KEY,empresa_id uuid,padrao text);
 CREATE TABLE fotos_materiais(material_id uuid REFERENCES materiais ON DELETE CASCADE,url text,thumbnail_url text);
 CREATE TABLE notificacoes(user_id uuid,tipo text,titulo text,mensagem text,material_id uuid REFERENCES materiais ON DELETE CASCADE);
 INSERT INTO empresas VALUES('${owner}','${owner}');
 INSERT INTO materiais VALUES('${material}','${owner}','Freijó');
 INSERT INTO fotos_materiais VALUES('${material}','photo','thumb');`);
 await db.exec(migration);
 const reject=(who,reason)=>db.query('SELECT reject_material_with_reason($1,$2,$3) result',[who,material,reason]);
 await assert.rejects(reject(owner,'Foto incorreta'),/forbidden/);
 await assert.rejects(reject(actor,'  '),/invalid_reason/);
 await assert.rejects(reject(actor,'a'.repeat(1001)),/invalid_reason/);
 await db.exec('SET ROLE authenticated');
 await assert.rejects(reject(actor,'Foto incorreta'),/permission denied/);
 await db.exec('RESET ROLE');
 await db.exec("ALTER TABLE notificacoes ADD CONSTRAINT fail_notice CHECK (tipo <> 'anuncio_excluido')");
 await assert.rejects(reject(actor,'Foto incorreta'),/fail_notice/);
 assert.equal((await db.query('SELECT * FROM materiais')).rows.length,1);
 assert.equal((await db.query('SELECT * FROM fotos_materiais')).rows.length,1);
 assert.equal((await db.query('SELECT * FROM material_rejections')).rows.length,0);
 await db.exec('ALTER TABLE notificacoes DROP CONSTRAINT fail_notice');
 await db.exec('SET ROLE service_role');
 const result=await reject(actor,'  Foto incorreta  ');
 assert.equal(result.rows[0].result.ok,true);
 await reject(actor,'Foto incorreta');
 await db.exec('RESET ROLE');
 assert.equal((await db.query('SELECT * FROM materiais')).rows.length,0);
 assert.equal((await db.query('SELECT * FROM fotos_materiais')).rows.length,0);
 const notices=(await db.query('SELECT * FROM notificacoes')).rows;
 assert.equal(notices.length,1);
 assert.equal(notices[0].user_id,owner);
 assert.equal(notices[0].material_id,null);
 assert.equal(notices[0].mensagem,'Seu anúncio "Freijó" foi excluído pela administração. Motivo: Foto incorreta');
 assert.equal((await db.query('SELECT * FROM material_rejections')).rows.length,1);
 } finally {await db.close();}
});
